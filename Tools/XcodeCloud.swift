import Foundation

struct CloudError: Error, CustomStringConvertible {
    let description: String
    init(_ description: String) { self.description = description }
}
struct CommandFailure: Error, CustomStringConvertible {
    let status: Int32
    let phase: String
    let tool: String
    var description: String { "\(phase) failed: \(tool) exited with status \(status). See the command output above." }
}
func cloudLog(_ message: String) {
    FileHandle.standardError.write(Data("[Mossling Cloud] \(message)\n".utf8))
}
struct Product: Decodable { let bundleIdentifier: String; let marketingVersion: String }
// Native Xcode Cloud actions own signing and select DEVELOPMENT_TEAM.
// CI_TEAM_ID is service metadata, not an input to our generated build settings.
struct CloudIdentity {
    let bundleID: String
    let build: String
    var configuration: String {
        "// Generated by Xcode Cloud; never commit.\nCURRENT_PROJECT_VERSION = \(build)\n"
    }
}
func requireCloud(_ condition: Bool, _ message: String) throws {
    guard condition else { throw CloudError(message) }
}
func matches(_ value: String, _ expression: String) -> Bool {
    value.range(of: expression, options: .regularExpression)?.lowerBound == value.startIndex
        && value.range(of: expression, options: .regularExpression)?.upperBound == value.endIndex
}
func identity(_ environment: [String: String], product: Product) throws -> CloudIdentity {
    let bundle = environment["CI_BUNDLE_ID"] ?? ""
    let build = environment["CI_BUILD_NUMBER"] ?? ""
    try requireCloud(environment["CI"] == "TRUE", "This adapter requires Xcode Cloud (CI=TRUE).")
    try requireCloud(matches(product.bundleIdentifier, #"[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+"#)
        && !product.bundleIdentifier.lowercased().hasPrefix("com.example."), "Product identity must be concrete.")
    try requireCloud(bundle == product.bundleIdentifier, "CI_BUNDLE_ID must match Config/Product.json.")
    try requireCloud(matches(build, #"[1-9][0-9]{0,17}"#), "CI_BUILD_NUMBER must be a positive decimal integer.")
    return CloudIdentity(bundleID: bundle, build: build)
}
func nativeAction(_ environment: [String: String]) throws -> (String, Int32) {
    guard let action = environment["CI_XCODEBUILD_ACTION"],
          ["analyze", "archive", "build", "build-for-testing", "test-without-building"].contains(action),
          let raw = environment["CI_XCODEBUILD_EXIT_CODE"],
          let status = Int32(raw), (0...255).contains(status) else {
        throw CloudError("Missing or invalid Xcode Cloud action/exit status.")
    }
    return (action, status)
}
@discardableResult
func run(_ executable: String, _ arguments: [String], at directory: URL? = nil,
         environment: [String: String]? = nil, capture: Bool = false,
         phase: String, log: (String) -> Void = cloudLog) throws -> String {
    // Log only authored phase labels and the executable name, never arguments or environment.
    let tool = URL(fileURLWithPath: executable).lastPathComponent
    let started = ProcessInfo.processInfo.systemUptime
    log("Starting \(phase) (\(tool)).")
    let process = Process()
    process.executableURL = URL(fileURLWithPath: executable)
    process.arguments = arguments
    process.currentDirectoryURL = directory
    process.environment = environment
    let output = capture ? Pipe() : nil
    if let output { process.standardOutput = output }
    do { try process.run() }
    catch {
        log("\(phase) could not launch \(tool). Check tool installation and executable permissions.")
        throw CloudError("\(phase): could not launch \(tool).")
    }
    let data = output?.fileHandleForReading.readDataToEndOfFile()
    process.waitUntilExit()
    let elapsed = String(format: "%.1f", ProcessInfo.processInfo.systemUptime - started)
    guard process.terminationReason == .exit && process.terminationStatus == 0 else {
        // A signal number is not an exit code; preserve the usual shell convention.
        let status = process.terminationReason == .uncaughtSignal
            ? 128 + process.terminationStatus : max(1, process.terminationStatus)
        let failure = CommandFailure(status: status, phase: phase, tool: tool)
        log("\(failure) Elapsed: \(elapsed)s.")
        throw failure
    }
    log("Finished \(phase) in \(elapsed)s.")
    return data.map { String(decoding: $0, as: UTF8.self) } ?? ""
}
func bootstrapMise(root: URL) throws -> URL {
    #if os(macOS)
    #if arch(arm64)
    let architecture = "arm64"
    let checksum = "bbfd47ef65c2278c4e9ba09b523beb1019365a3c0b9c9fc60f686dc16f358e0f"
    #elseif arch(x86_64)
    let architecture = "x64"
    let checksum = "167137820c857491cc649c5502276ad94e31edb4a5e9e6339aed8d812031d031"
    #else
    throw CloudError("Unsupported macOS architecture.")
    #endif
    // Official v2026.9.11 release asset digests; no mutable installer or Homebrew state.
    let directory = root.appendingPathComponent(".build-artifacts/cloud-tools")
    try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    let binary = directory.appendingPathComponent("mise")
    try run("/usr/bin/curl", ["--fail", "--location", "--silent", "--show-error", "--retry", "3",
        "--proto", "=https", "--proto-redir", "=https", "--connect-timeout", "30", "--max-time", "300",
        "--output", binary.path,
        "https://github.com/jdx/mise/releases/download/v2026.9.11/mise-v2026.9.11-macos-\(architecture)"], phase: "download pinned mise")
    let actual = try run("/usr/bin/shasum", ["-a", "256", binary.path], capture: true, phase: "verify mise SHA256").split(separator: " ").first
    try requireCloud(actual == Substring(checksum), "mise checksum mismatch; refusing to execute downloaded binary.")
    try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: binary.path)
    return binary
    #else
    throw CloudError("Xcode Cloud bootstrap requires macOS.")
    #endif
}
func cloudMain(_ arguments: [String], environment: [String: String]) throws {
    try requireCloud(arguments.count == 3, "Usage: XcodeCloud.swift <post-clone|post-xcodebuild> <ci_scripts path>")
    let scripts = URL(fileURLWithPath: arguments[2], isDirectory: true)
    if arguments[1] == "post-xcodebuild" {
        let (action, status) = try nativeAction(environment)
        // Preserve the original native failure even if artifacts or identity are unavailable.
        guard status == 0 else { throw CommandFailure(status: status, phase: "native \(action)", tool: "xcodebuild") }
        guard action == "archive" else { return }
        let product = try JSONDecoder().decode(Product.self, from: Data(contentsOf: scripts.appendingPathComponent("Product.json")))
        let values = try identity(environment, product: product)
        guard let archive = environment["CI_ARCHIVE_PATH"], archive.hasPrefix("/"),
              FileManager.default.fileExists(atPath: archive) else {
            throw CloudError("Successful archive action requires an existing absolute CI_ARCHIVE_PATH.")
        }
        try run("/usr/bin/env", ["swift", scripts.appendingPathComponent("helpers/CheckArchive.swift").path,
            archive, "--expect-bundle-id", values.bundleID, "--expect-build-number", values.build,
            "--expect-version", product.marketingVersion], phase: "validate archive identity and packaging")
        return
    }
    try requireCloud(arguments[1] == "post-clone", "Unknown Xcode Cloud phase.")
    guard let path = environment["CI_PRIMARY_REPOSITORY_PATH"], path.hasPrefix("/") else {
        throw CloudError("CI_PRIMARY_REPOSITORY_PATH must be an absolute checkout path.")
    }
    cloudLog("Validating product identity and writing the Cloud build number.")
    let root = URL(fileURLWithPath: path, isDirectory: true)
    let product = try JSONDecoder().decode(Product.self, from: Data(contentsOf: root.appendingPathComponent("Config/Product.json")))
    let values = try identity(environment, product: product)
    try values.configuration.write(to: root.appendingPathComponent("Config/Cloud.xcconfig"), atomically: true, encoding: .utf8)
    let mise = try bootstrapMise(root: root)
    var child = environment
    child["MISE_YES"] = "1"
    child["MISE_TRUSTED_CONFIG_PATHS"] = root.path
    child["PATH"] = mise.deletingLastPathComponent().path + ":" + (environment["PATH"] ?? "/usr/bin:/bin")
    try run(mise.path, ["install", "--locked"], at: root, environment: child, phase: "install locked tools")
    try run(mise.path, ["run", "--jobs", "1", "cloud:prepare"], at: root, environment: child, phase: "verify domain tests and generated project")
}
